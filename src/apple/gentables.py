#!/usr/bin/env python3
"""Generates tables.s, the lookup tables the Apple II utilities use:

- the Soft-70 font: printable ASCII ($20-$7E) in 4x8 cells, one byte per
  scan line with bit 0 the leftmost pixel, derived from the Tom Thumb font
  (Robey Pointer's 3x5 font, CC0; see NOTICE) as Adafruit GFX publishes it
  in Fonts/TomThumb.h -- pass that file's path as the argument;
- the shift and mask tables that place a 4-pixel cell at any of the seven
  bit positions within a Hi-Res byte pair;
- the byte and shift for each of the 70 Soft-70 columns;
- a CP437-to-ASCII map for characters $80-$FF, so the PC box-drawing and
  block characters BBS screens use come out as + - | #.

Run: python3 gentables.py TomThumb.h > tables.s
"""
import re
import sys


def tom_thumb(path):
    text = open(path).read()
    start = text.index("TomThumbBitmaps")
    bitmap_src = re.sub(r"/\*.*?\*/", "", text[start:text.index("};", start)], flags=re.S)
    bitmap_src = bitmap_src[bitmap_src.index("{"):]
    bitmaps = [int(b, 16) for b in re.findall(r"0x([0-9A-Fa-f]{2})", bitmap_src)]
    glyph_src = text[text.index("TomThumbGlyphs"):]
    glyphs = re.findall(r"\{\s*(\d+),\s*(\d+),\s*(\d+),\s*(\d+),\s*(-?\d+),\s*(-?\d+)\s*\},\s*/\*\s*0x([0-9A-Fa-f]+)", glyph_src)
    cells = {}
    for offset, width, height, _advance, x_off, y_off, code in glyphs:
        code = int(code, 16)
        if not 0x20 <= code <= 0x7E:
            continue
        offset, width, height, x_off, y_off = map(int, (offset, width, height, x_off, y_off))
        rows = [0] * 8
        bit = 0
        for j in range(height):
            for i in range(width):
                byte = bitmaps[offset + bit // 8]
                if byte & (0x80 >> (bit % 8)):
                    row = 6 + y_off + j          # baseline on row 6: caps on rows 1-5, descenders on 6
                    col = x_off + i
                    if 0 <= row < 8 and 0 <= col < 4:
                        rows[row] |= 1 << col
                bit += 1
        cells[code] = rows
    missing = [hex(c) for c in range(0x20, 0x7F) if c not in cells]
    if missing:
        sys.exit("missing glyphs: " + ", ".join(missing))
    return cells


def cp437():
    table = []
    for c in range(0x80, 0x100):
        if c in (0xB3, 0xBA):
            table.append(ord("|"))
        elif c in (0xC4, 0xCD):
            table.append(ord("-"))
        elif 0xB4 <= c <= 0xDA:
            table.append(ord("+"))
        elif c in (0xB0, 0xB1, 0xB2, 0xDB, 0xDC, 0xDD, 0xDE, 0xDF, 0xFE):
            table.append(ord("#"))
        elif c in (0xF9, 0xFA):
            table.append(ord("."))
        else:
            table.append(ord("?"))
    return table


def rows(values, per_line=16):
    for i in range(0, len(values), per_line):
        yield "        .byte " + ",".join("$%02X" % v for v in values[i:i + per_line])


def main():
    cells = tom_thumb(sys.argv[1])
    out = ["; Generated by gentables.py -- edit that, not this.", "",
           ".export s70_font, s70_shift_lo, s70_shift_hi, s70_keep_lo, s70_keep_hi",
           ".export s70_col_byte, s70_col_shift, cp437_map", "", ".rodata", ""]
    out.append("; Soft-70 font: 8 bytes per character from $20, bit 0 leftmost")
    out.append("s70_font:")
    for code in range(0x20, 0x7F):
        out.append("        .byte " + ",".join("$%02X" % v for v in cells[code]) + "  ; " + repr(chr(code)))
    lo = [((g << s) & 0x7F) for s in range(7) for g in range(16)]
    hi = [((g << s) >> 7) for s in range(7) for g in range(16)]
    out += ["", "; a 4-bit cell row shifted left 0-6: low 7 bits, then the bits that spill into the next byte",
            "s70_shift_lo:"] + list(rows(lo)) + ["s70_shift_hi:"] + list(rows(hi))
    keep_lo = [(~(0x0F << s) & 0x7F) | 0x80 for s in range(7)]
    keep_hi = [(~((0x0F << s) >> 7) & 0x7F) | 0x80 for s in range(7)]
    out += ["", "; the bits of each byte a cell at shift 0-6 leaves alone",
            "s70_keep_lo:"] + list(rows(keep_lo)) + ["s70_keep_hi:"] + list(rows(keep_hi))
    out += ["", "; Soft-70 column 0-69: its Hi-Res byte (4 pixels a column, 7 a byte) and bit position",
            "s70_col_byte:"] + list(rows([(4 * x) // 7 for x in range(70)])) + \
           ["s70_col_shift:"] + list(rows([(4 * x) % 7 for x in range(70)]))
    out += ["", "; CP437 $80-$FF as ASCII: box drawing to + - |, blocks to #, the rest ?",
            "cp437_map:"] + list(rows(cp437()))
    print("\n".join(out))


main()
